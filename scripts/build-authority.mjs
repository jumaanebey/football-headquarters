// Bundle the club-authority Edge Function from its TypeScript entry into the single-file
// `index.ts` that Supabase deploys. The entry (`main.ts`) imports shared game modules from
// the repository root, so the server executes exactly the rules the client ships.
//
//   npm run authority:build
//
// The previous deployment (version 2, 2026-09-10) was produced the same way but its sources
// were never committed; `supabase/recovery/club-authority.v2.bundle.js` preserves that
// artifact verbatim and docs/AUTHORITY-RECOVERY.md records how the sources were recovered.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = resolve(root, 'supabase/functions/club-authority/main.ts');
const outfile = resolve(root, 'supabase/functions/club-authority/index.ts');
const check = process.argv.includes('--check');

const result = await build({
  entryPoints: [entry], bundle: true, write: false, format: 'esm', platform: 'neutral', target: 'esnext',
  logLevel: 'warning', legalComments: 'none',
});
const banner = '// GENERATED by scripts/build-authority.mjs from main.ts — do not edit; run `npm run authority:build`.\n';
const code = banner + result.outputFiles[0].text;
const digest = createHash('sha256').update(code).digest('hex');
if (check) {
  const current = await readFile(outfile, 'utf8').catch(() => '');
  if (current !== code) { console.error(`club-authority bundle is stale (expected sha256 ${digest}); run npm run authority:build`); process.exit(1); }
  console.log(`club-authority bundle is current (sha256 ${digest})`);
} else {
  await writeFile(outfile, code);
  console.log(`wrote ${outfile} (${code.length} bytes, sha256 ${digest})`);
}
