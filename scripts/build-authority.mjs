// Bundle the club-authority Edge Function from its TypeScript entry into the single-file
// `index.ts` that Supabase deploys. The entry (`main.ts`) imports shared game modules from
// the repository root, so the server executes exactly the rules the client ships.
//
//   npm run authority:build            regenerate index.ts
//   npm run authority:build -- --check parity guard: sources ↔ index.ts ↔ staged/deployed artifacts ↔ deployed.json
//   npm run authority:build -- --artifact N   also write supabase/recovery/club-authority.vN.min.js (the deploy artifact)
//   --require-deployed-current         make a lagging deployment a failure (release gate before shipping a client)
//
// The previous deployment (version 2, 2026-09-10) was produced the same way but its sources
// were never committed; `supabase/recovery/club-authority.v2.bundle.js` preserves that
// artifact verbatim and docs/AUTHORITY-RECOVERY.md records how the sources were recovered.
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkAuthorityParity, sha256, findSecretShapes } from './authority-parity.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = resolve(root, 'supabase/functions/club-authority/main.ts');
const outfile = resolve(root, 'supabase/functions/club-authority/index.ts');
const args = process.argv.slice(2);
const check = args.includes('--check');
const artifactArg = args.indexOf('--artifact');

const common = { entryPoints: [entry], bundle: true, write: false, format: 'esm', platform: 'neutral', target: 'esnext', logLevel: 'warning', legalComments: 'none' };
const banner = '// GENERATED by scripts/build-authority.mjs from main.ts — do not edit; run `npm run authority:build`.\n';
const readable = banner + (await build(common)).outputFiles[0].text;
// Byte-identical to `esbuild main.ts --bundle --minify --line-limit=220` (the documented packaging command).
const minified = (await build({ ...common, minify: true, lineLimit: 220 })).outputFiles[0].text;

if (check) {
  const result = await checkAuthorityParity({ root, readable, minified, requireDeployedCurrent: args.includes('--require-deployed-current') });
  for (const line of result.lines) console.log(`${{ pass: 'PASS', fail: 'FAIL', info: 'INFO' }[line.level]}  ${line.text}`);
  console.log(result.ok ? `RESULT: authority parity holds (deployment ${result.deployment})` : 'RESULT: authority parity broken');
  process.exit(result.ok ? 0 : 1);
}
if (findSecretShapes(readable).length || findSecretShapes(minified).length) { console.error('refusing to write a bundle that contains a token-shaped string'); process.exit(1); }
await writeFile(outfile, readable);
console.log(`wrote ${outfile} (${readable.length} bytes, sha256 ${sha256(readable)})`);
if (artifactArg >= 0) {
  const version = Number(args[artifactArg + 1]);
  if (!Number.isInteger(version) || version < 4) { console.error('--artifact needs a version number (4 or later; v2/v3 are preserved history)'); process.exit(1); }
  const artifact = resolve(root, `supabase/recovery/club-authority.v${version}.min.js`);
  await writeFile(artifact, minified);
  console.log(`wrote ${artifact} (${minified.length} bytes, sha256 ${sha256(minified)}) — record it in supabase/recovery/deployed.json as staged`);
}
